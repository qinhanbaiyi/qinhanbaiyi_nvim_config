-- 基础编辑习惯集中在这里，插件专属选项放在 lua/plugins/ 对应文件。
vim.opt.number = true -- 显示绝对行号，便于定位报错行
vim.opt.relativenumber = true -- 同时显示相对行号，便于按数量移动
vim.opt.cursorline = true -- 高亮光标所在行
vim.opt.expandtab = false -- 全局保留真实 Tab，各语言可通过局部设置或格式化器覆盖
vim.opt.scrolloff = 5 -- 光标上下尽量保留 5 行上下文
vim.opt.wrap = true -- 长行在屏幕内折行，不向文件插入换行
vim.opt.foldenable = true -- 允许折叠，具体折叠方式由文件类型决定
vim.opt.colorcolumn = "100" -- 第 100 列显示参考线，不强制截断内容
vim.opt.signcolumn = "yes:2" -- 固定两列标记区，减少诊断和 Git 标记造成的文字跳动
vim.opt.mouse = "a" -- 所有模式可使用鼠标
vim.opt.showcmd = true -- 显示尚未完成的命令序列
vim.opt.splitright = true -- 垂直分屏默认在右侧
vim.opt.splitbelow = true -- 水平分屏默认在下方
vim.opt.ignorecase = true -- 搜索默认忽略大小写
vim.opt.wildmenu = true -- 保留命令行候选菜单
vim.opt.smartcase = true -- 搜索词含大写字母时恢复区分大小写
vim.opt.updatetime = 100 -- 空闲更新等待 100ms，影响 CursorHold 等事件
vim.opt.ttyfast = true -- 保留快速终端兼容选项
vim.opt.visualbell = true -- 沿用可视响铃偏好
vim.opt.hidden = true -- 切换缓冲区时允许保留尚未保存的内容
vim.opt.termguicolors = true -- 启用终端真彩色
vim.g.onedark_terminal_italics = 2 -- 保留旧主题的终端斜体兼容变量
